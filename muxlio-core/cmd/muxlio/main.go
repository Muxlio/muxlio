const usage = `muxlio — workflow execution engine

Usage:
  muxlio init [--agent name] [--allow-command]        Initialize ~/.muxlio and configure agent skills
  muxlio build <workflow.ts|plan.json> [--out file]    Compile workflow to canonical Plan IR
  muxlio check <workflow.ts|plan.json>                Validate a workflow or plan
  muxlio test <workflow.ts|plan.json> --input in.json  Test run with fake executor
  muxlio run <workflow.ts|plan.json> [input.json]     Run a plan (fake or real executor; or --server to submit remotely)
  muxlio graph <workflow.ts|plan.json|run-id>         Display DAG visualization (ascii, json, mermaid)
  muxlio inspect <workflow.ts|plan.json|run-id>       Print plan structure or run status
  muxlio snapshots <run-id> [--current] [--attempt ID] Inspect intermediate artifacts
  muxlio events <run-id> [--since seq] [--limit N]    Print run execution events
  muxlio gc [--apply TOKEN]                          Preview or apply offline retention cleanup
  muxlio artifacts <run-id>                           List artifacts generated by run
  muxlio signal <run-id> --name <sig> [--data file]   Deliver external signal to waiting run
  muxlio runs [--data-dir dir] [--state state]             List runs in --data-dir (optionally filtered by state)
  muxlio ui [--server URL] [--port port] [--open]     Launch or open the Observability UI
  muxlio env [--shell bash|zsh|fish]                  Display or export environment configuration
  muxlio doctor [--server URL]                        Run installation and environment health checks
  muxlio upgrade [--prefix dir]                       Upgrade Muxlio runtime from source repository
  muxlio server start|install                         Start or install the coordinator server
  muxlio worker start --workspace dir                 Connect an outbound remote worker (auto-detects capabilities)
  muxlio service start [--config path]                Start supervised coordinator, worker and UI (background)
  muxlio service stop [--config path]                 Stop the running service
  muxlio service restart [--config path]              Stop then start the service (start if not running)
  muxlio submit [--server URL] plan.json input.json    Submit a durable run
  muxlio status [--server URL] [run-id]                Query remote run status
  muxlio pause|resume|cancel [--server URL] run-id      Control a remote run
  muxlio test-event --server URL --secret-file FILE [--idempotency-key KEY] trigger-id payload.json
                                                   Send a signed webhook (creates a real run)
  muxlio version                                      Print version info

Options:
  --json                  Emit machine-readable JSON output
  --server <profile|URL>  Coordinator profile name (from ~/.muxlio/config.json) or explicit URL
  --token <token>         Client bearer authentication token
  --token-file <file>     File containing client bearer authentication token
  --worker-token <token>  Worker authentication token (worker start)
  --worker-token-file <file>
                          File containing worker authentication token
  --fake-config <file>    JSON file with fake executor configuration
  muxlio worker status [--adapters DIR] [--json]      Probe local executor readiness

  --adapters <dir>        Directory of executor adapter scripts (real execution)
  --workspace <dir>       Authorized workspace for standalone run (or MUXLIO_WORKSPACE)
                          Worker start uses this as the worker-local adapter workspace
  --data-dir <dir>        Runtime data directory (default: ~/.muxlio)
  --addr <host:port>      Address for server to listen on (default: 127.0.0.1:7600)
`

func main() {
	if len(os.Args) < 2 {
		fmt.Print(usage)
		os.Exit(1)
	}

	jsonOut := false
	fakeConfig := ""
	dataDir := defaultRuntime()
	adaptersDir := ""
	workspace := os.Getenv("MUXLIO_WORKSPACE")
	addr := "127.0.0.1:7600"
	workerCoordinator, workerID, workerCapabilities, workerCapacity := "", "", "", ""
	serverFlag := ""
	tokenFlag := ""
	tokenFileFlag := ""
	workerTokenFlag := ""
	workerTokenFileFlag := ""
	var stateFilters []string
	raw := os.Args[1:]
	before, args := partitionArgs(raw)
	if len(args) == 0 && len(before) > 0 {
		args = before
		before = nil
	}
	for i := 0; i < len(before); i++ {
		switch before[i] {
		case "--json":
			jsonOut = true
		case "--fake-config":
			i++
			if i < len(before) {
				fakeConfig = before[i]
			}
		case "--data-dir":
			i++
			if i < len(before) {
				dataDir = before[i]
			}
		case "--adapters":
			i++
			if i < len(before) {
				adaptersDir = before[i]
			}
		case "--workspace":
			i++
			if i < len(before) {
				workspace = before[i]
			}
		case "--addr":
			i++
			if i < len(before) {
				addr = before[i]
			}
		case "--coordinator":
			i++
			if i < len(before) {
				workerCoordinator = before[i]
			}
		case "--worker-id":
			i++
			if i < len(before) {
				workerID = before[i]
			}
		case "--capabilities":
			i++
			if i < len(before) {
				workerCapabilities = before[i]
			}
		case "--capacity":
			i++
			if i < len(before) {
				workerCapacity = before[i]
			}
		case "--state":
			i++
			if i < len(before) {
				// Accept comma-separated states or repeated --state flags.
				stateFilters = append(stateFilters, parseStateFlag(before[i])...)
			}
		case "--server":
			i++
			if i < len(before) {
				serverFlag = before[i]
			}
		case "--token":
			i++
			if i < len(before) {
				tokenFlag = before[i]
			}
		case "--token-file":
			i++
			if i < len(before) {
				tokenFileFlag = before[i]
			}
		case "--worker-token":
			i++
			if i < len(before) {
				workerTokenFlag = before[i]
			}
		case "--worker-token-file":
			i++
			if i < len(before) {
				workerTokenFileFlag = before[i]
			}
		}
	}
	if argvIncludesJSON(raw) {
		jsonOut = true
	}

	if len(args) == 0 {
		fmt.Print(usage)
		os.Exit(1)
	}

	cmd := args[0]
	if jsonOut && (cmd == "run" || cmd == "test") {
		// Keep stdout a single JSON result for callers of the local CLI.
		coordinatorlog.SetOutput(os.Stderr)
	}
	switch cmd {
	case "init":
		os.Exit(cmdInit(args[1:], dataDir, jsonOut))

	case "build":
		os.Exit(cmdBuild(args[1:], jsonOut))

	case "check":
		if len(args) < 2 {
			die("check requires a workflow or plan file path")
		}
		os.Exit(cmdCheck(args[1], jsonOut))

	case "test":
		testArgs := args[1:]
		// Global parsing consumes this shared flag; preserve it for fake tests.
		if fakeConfig != "" {
			testArgs = append(testArgs, "--fake-config", fakeConfig)
		}
		os.Exit(cmdTest(testArgs, jsonOut))

	case "run":
		if len(args) < 2 {
			die("run requires a plan file path (and optionally an input file path)")
		}
		runArgs := args[1:]
		runArgs, workspace = absorbFlagValue("workspace", runArgs, workspace)
		runArgs, fakeConfig = absorbFlagValue("fake-config", runArgs, fakeConfig)
		runArgs, serverFlag = absorbFlagValue("server", runArgs, serverFlag)
		runArgs, dataDir = absorbFlagValue("data-dir", runArgs, dataDir)
		runArgs = withoutArg(runArgs, "--json")
		if len(runArgs) < 1 {
			die("run requires a plan file path (and optionally an input file path)")
		}
		inputArg := ""
		if len(runArgs) >= 2 {
			inputArg = runArgs[1]
		}
		os.Exit(cmdRun(runArgs[0], inputArg, fakeConfig, adaptersDir, dataDir, workspace, serverFlag, tokenFlag, tokenFileFlag, jsonOut))

	case "graph":
		os.Exit(cmdGraph(args[1:], dataDir, jsonOut))

	case "inspect":
		if len(args) < 2 {
			die("inspect requires a plan file path or run id")
		}
		os.Exit(runInspect(args[1], dataDir, jsonOut))

	case "snapshots":
		os.Exit(cmdSnapshots(args[1:], dataDir, jsonOut))
	case "events":
		os.Exit(cmdEvents(args[1:], dataDir, jsonOut))

	case "gc":
		os.Exit(cmdGC(args[1:], dataDir))
	case "artifacts":
		os.Exit(cmdArtifacts(args[1:], dataDir, jsonOut))

	case "signal":
		os.Exit(cmdSignal(forwardRemoteFlags(args[1:], serverFlag, tokenFlag, tokenFileFlag), dataDir))

	case "test-event":
		os.Exit(cmdTestEvent(forwardRemoteFlags(args[1:], serverFlag, tokenFlag, tokenFileFlag), dataDir))

	case "service":
		os.Exit(cmdService(args[1:]))

	case "submit", "status", "pause", "resume", "cancel":
		os.Exit(cmdRemote(cmd, forwardRemoteFlags(args[1:], serverFlag, tokenFlag, tokenFileFlag), dataDir))

	case "runs":
		runTail := args[1:]
		var extra []string
		for i := 0; i < len(runTail); i++ {
			switch runTail[i] {
			case "--data-dir":
				if i+1 < len(runTail) {
					dataDir = runTail[i+1]
					i++
				}
			case "--state":
				if i+1 < len(runTail) {
					extra = append(extra, parseStateFlag(runTail[i+1])...)
					i++
				}
			}
		}
		os.Exit(cmdRuns(dataDir, append(stateFilters, extra...), jsonOut))

	case "ui":
		os.Exit(cmdUI(forwardServerFlag(args[1:], serverFlag), jsonOut))

	case "env":
		os.Exit(cmdEnv(args[1:], dataDir, jsonOut))

	case "doctor":
		os.Exit(cmdDoctor(args[1:], dataDir, jsonOut))

	case "upgrade":
		os.Exit(cmdUpgrade(args[1:], dataDir, jsonOut))

	case "server":
		if len(args) < 2 {
			die("usage: muxlio server <start|install>")
		}
		switch args[1] {
		case "start":
			os.Exit(cmdServerStart(dataDir, addr, jsonOut))
		case "install":
			os.Exit(cmdServerInstall(args[2:]))
		default:
			die("usage: muxlio server <start|install>")
		}

	case "worker":
		workerArgs := args[1:]
		workerArgs, workspace = absorbFlagValue("workspace", workerArgs, workspace)
		workerArgs, workerCoordinator = absorbFlagValue("coordinator", workerArgs, workerCoordinator)
		workerArgs, workerID = absorbFlagValue("worker-id", workerArgs, workerID)
		workerArgs, workerCapabilities = absorbFlagValue("capabilities", workerArgs, workerCapabilities)
		workerArgs, workerCapacity = absorbFlagValue("capacity", workerArgs, workerCapacity)
		workerArgs, workerTokenFlag = absorbFlagValue("worker-token", workerArgs, workerTokenFlag)
		workerArgs, workerTokenFileFlag = absorbFlagValue("worker-token-file", workerArgs, workerTokenFileFlag)
		if len(workerArgs) > 0 && workerArgs[0] == "status" {
			os.Exit(cmdWorkerStatus(dataDir, adaptersDir, jsonOut))
		}
		if len(workerArgs) < 1 || workerArgs[0] != "start" {
			die("usage: muxlio worker start --coordinator URL --worker-id ID --workspace DIR [--capabilities name1,name2] [--worker-token TOKEN | --worker-token-file FILE]")
		}
		os.Exit(cmdWorkerStart(workerCoordinator, workerID, workerCapabilities, workerCapacity, adaptersDir, dataDir, workspace, addr, workerTokenFlag, workerTokenFileFlag))

	case "version":
		fmt.Printf("muxlio %s (Plan IR v1.0)\n", CurrentVersion)

	default:
		fmt.Fprintf(os.Stderr, "error: unknown command %q\n", cmd)
		fmt.Print(usage)
		os.Exit(2)
	}
}

func forwardServerFlag(args []string, server string) []string {
	if server == "" {
		return args
	}
	return append([]string{"--server", server}, args...)
}

// forwardRemoteFlags prepends global coordinator client flags when they were
// parsed before the subcommand (muxlio --server URL status …).
func forwardRemoteFlags(args []string, server, token, tokenFile string) []string {
	var prefix []string
	if server != "" {
		prefix = append(prefix, "--server", server)
	}
	if token != "" {
		prefix = append(prefix, "--token", token)
	}
	if tokenFile != "" {
		prefix = append(prefix, "--token-file", tokenFile)
	}
	return append(prefix, args...)
}

func die(msg string) {
	fmt.Fprintln(os.Stderr, "error:", msg)
	os.Exit(2)
}

func loadPlan(path string) (*plan.Plan, error) {
	ext := strings.ToLower(filepath.Ext(path))
	if ext == ".ts" || ext == ".js" || ext == ".mjs" {
		abs, err := filepath.Abs(path)
		if err != nil {
			return nil, err
		}
		raw, err := compileTypeScriptWorkflow(abs)
		if err != nil {
			return nil, err
		}
		var p plan.Plan
		if err := json.Unmarshal(raw, &p); err != nil {
			return nil, fmt.Errorf("parsing compiled plan JSON: %w", err)
		}
		return &p, nil
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading plan: %w", err)
	}
	var p plan.Plan
	if err := json.Unmarshal(data, &p); err != nil {
		return nil, fmt.Errorf("parsing plan JSON: %w", err)
	}
	return &p, nil
}

// fakeConfig holds the fake executor configuration loaded from --fake-config.
type fakeConfigJSON struct {
	ByNode     map[string]workerResult `json:"byNode"`
	ByExecutor map[string]workerResult `json:"byExecutor"`
}

type workerResult struct {
	Outputs map[string]any `json:"outputs"`
	Error   string         `json:"error,omitempty"`
}

func loadFakeExecutor(configPath string) (*workers.FakeExecutor, error) {
	exec := workers.NewFake()
	if configPath == "" {
		return exec, nil
	}
	data, err := os.ReadFile(configPath)
	if err != nil {
		return nil, fmt.Errorf("reading fake config: %w", err)
	}
	var cfg fakeConfigJSON
	if err := json.Unmarshal(data, &cfg); err != nil {
		return nil, fmt.Errorf("parsing fake config: %w", err)
	}
	for nodeID, result := range cfg.ByNode {
		exec.ByNode(nodeID, workers.ExecuteResult{
			Outputs: result.Outputs,
			Error:   result.Error,
		})
	}
	for executor, result := range cfg.ByExecutor {
		exec.ByExecutor(executor, workers.ExecuteResult{
			Outputs: result.Outputs,
			Error:   result.Error,
		})
	}
	return exec, nil
}

func cmdCheck(path string, jsonOut bool) int {
	absPath, err := filepath.Abs(path)
	if err != nil {
		emitDiagnostic(path, err, jsonOut)
		return 1
	}
	p, err := loadPlan(absPath)
	if err != nil {
		emitDiagnostic(path, err, jsonOut)
		return 1
	}
	allIssues := plan.Validate(p)
	for i := range allIssues {
		if allIssues[i].Source != nil && strings.EqualFold(filepath.Ext(path), ".json") {
			allIssues[i].Source.File = path
		}
	}

	// Split into hard errors and warnings.
	var errors, warnings []plan.ValidationError
	for _, ve := range allIssues {
		if ve.Severity == "warning" {
			warnings = append(warnings, ve)
		} else {
			errors = append(errors, ve)
		}
	}

	if len(errors) == 0 {
		// Run co-located workflow tests for TypeScript/JS sources.
		ext := strings.ToLower(filepath.Ext(absPath))
		if ext == ".ts" || ext == ".js" || ext == ".mjs" {
			if testErr := runWorkflowTests(absPath, jsonOut); testErr != "" {
				if jsonOut {
					out, _ := diagnostic.JSON(map[string]any{"valid": false, "errors": []diagnostic.Diagnostic{diagnostic.New("MUXLIO_WORKFLOW_TEST_FAILED", "build", testErr, "Fix the failing workflow test and rerun check.")}, "warnings": warnings, "digest": p.Digest})
					fmt.Println(string(out))
				} else {
					fmt.Fprintf(os.Stderr, "✗ %s\n", diagnostic.Redact(testErr))
				}
				return 1
			}
		}

		if jsonOut {
			out, _ := diagnostic.JSON(map[string]any{"valid": true, "digest": p.Digest, "warnings": warnings})
			fmt.Println(string(out))
		} else {
			// Surface warnings even when the plan is structurally valid.
			for _, w := range warnings {
				loc := ""
				if w.Subgraph != "" {
					loc = " [" + w.Subgraph
					if w.NodeID != "" {
						loc += "/" + w.NodeID
					}
					loc += "]"
				}
				fmt.Fprintf(os.Stderr, "  ⚠ %s: %s%s\n", w.Code, w.Message, loc)
				if w.Fix != "" {
					fmt.Fprintf(os.Stderr, "    fix: %s\n", w.Fix)
				}
			}
			fmt.Printf("✓ plan %q is valid (%d subgraphs)\n", p.Name, len(p.Subgraphs))
		}
		return 0
	}

	if jsonOut {
		out, _ := diagnostic.JSON(map[string]any{"valid": false, "errors": errors, "warnings": warnings})
		fmt.Println(string(out))
	} else {
		for _, ve := range warnings {
			loc := ""
			if ve.Subgraph != "" {
				loc = " [" + ve.Subgraph
				if ve.NodeID != "" {
					loc += "/" + ve.NodeID
				}
				loc += "]"
			}
			fmt.Fprintf(os.Stderr, "  ⚠ %s: %s%s\n", ve.Code, ve.Message, loc)
			if ve.Fix != "" {
				fmt.Fprintf(os.Stderr, "    fix: %s\n", ve.Fix)
			}
		}
		fmt.Fprintf(os.Stderr, "✗ plan %q has %d error(s):\n", p.Name, len(errors))
		for _, ve := range errors {
			loc := ""
			if ve.Subgraph != "" {
				loc = " [" + ve.Subgraph
				if ve.NodeID != "" {
					loc += "/" + ve.NodeID
				}
				loc += "]"
			}
			fmt.Fprintf(os.Stderr, "  %s: %s%s\n", ve.Code, ve.Message, loc)
			if ve.Fix != "" {
				fmt.Fprintf(os.Stderr, "    fix: %s\n", ve.Fix)
			}
		}
	}
	return 1
}

func openStore(dataDir string) (state.Store, error) {
	if dataDir == "" {
		return state.New(), nil
	}
	return sqlite.Open(filepath.Join(dataDir, "data", "coordinator.db"))
}

// validRunStates is the exhaustive set of states a run can be in.
var validRunStates = map[string]bool{
	"created":   true,
	"running":   true,
	"waiting":   true,
	"paused":    true,
	"succeeded": true,
	"failed":    true,
	"cancelled": true,
}

// parseStateFlag splits a comma-separated state value and trims whitespace from
// each element.  Empty tokens are discarded.  Repeated --state flags call this
// once per value and accumulate results in the caller.
func parseStateFlag(value string) []string {
	var out []string
	for _, s := range strings.Split(value, ",") {
		s = strings.TrimSpace(s)
		if s != "" {
			out = append(out, s)
		}
	}
	return out
}

func cmdRuns(dataDir string, stateFilters []string, jsonOut bool) int {
	if dataDir == "" {
		die("runs requires --data-dir")
	}
	store, err := openStore(dataDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		return 1
	}
	defer store.Close()
	return cmdRunsWithStore(store, stateFilters, jsonOut)
}

// cmdRunsWithStore is the testable core of cmdRuns.  It accepts an already-open
// store so that unit tests can inject an in-memory store without touching the
// filesystem.
func cmdRunsWithStore(store state.Store, stateFilters []string, jsonOut bool) int {
	// Validate any supplied state filters before querying the store.
	for _, s := range stateFilters {
		if !validRunStates[s] {
			valid := make([]string, 0, len(validRunStates))
			for k := range validRunStates {
				valid = append(valid, k)
			}
			// Sort for deterministic error message.
			sort.Strings(valid)
			fmt.Fprintf(os.Stderr, "error: unknown state %q; valid states: %s\n", s, strings.Join(valid, ", "))
			return 2
		}
	}

	runs, err := store.ListRuns()
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: listing runs: %v\n", err)
		return 1
	}

	// Apply state filter when one or more states were requested.
	if len(stateFilters) > 0 {
		want := make(map[string]bool, len(stateFilters))
		for _, s := range stateFilters {
			want[s] = true
		}
		kept := runs[:0]
		for _, r := range runs {
			if want[r.State] {
				kept = append(kept, r)
			}
		}
		runs = kept
	}

	if jsonOut {
		out, _ := json.MarshalIndent(map[string]any{"runs": runs}, "", "  ")
		fmt.Println(string(out))
		return 0
	}
	if len(runs) == 0 {
		fmt.Println("no runs")
		return 0
	}
	for _, r := range runs {
		fmt.Printf("%s  %s  %s\n", r.ID, r.State, r.WorkflowName)
	}
	return 0
}

func cmdRun(planPath, inputPath, fakeConfigPath, adaptersDir, dataDir, workspace, serverArg, tokenFlagVal, tokenFileFlagVal string, jsonOut bool) int {
	shutdownTelemetry, telemetryErr := setupTelemetry()
	if telemetryErr != nil {
		fmt.Fprintln(os.Stderr, telemetryErr)
		return 1
	}
	defer shutdownTelemetry()

	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stop()

	// If --server is provided, compile locally and submit to the remote coordinator.
	if serverArg != "" {
		return cmdRunRemote(ctx, planPath, inputPath, dataDir, serverArg, tokenFlagVal, tokenFileFlagVal, jsonOut)
	}

	p, err := loadPlan(planPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		return 1
	}
	verrs := plan.ErrorsOnly(plan.Validate(p))
	if len(verrs) > 0 {
		fmt.Fprintf(os.Stderr, "error: plan has %d validation error(s)\n", len(verrs))
		for _, ve := range verrs {
			fmt.Fprintf(os.Stderr, "  %s: %s\n", ve.Code, ve.Message)
		}
		return 1
	}

	inputData, err := os.ReadFile(inputPath)
	if err != nil {
		if inputPath == "" {
			inputData = []byte("{}")
		} else {
			fmt.Fprintf(os.Stderr, "error: reading input: %v\n", err)
			return 1
		}
	}

	var exec workers.Executor
	if adaptersDir != "" {
		workBase := filepath.Join(dataDir, "work")
		if dataDir == "" {
			workBase = filepath.Join(os.Getenv("HOME"), ".muxlio", "work")
		}
		if !filepath.IsAbs(workspace) {
			fmt.Fprintln(os.Stderr, "error: real execution requires an absolute --workspace or MUXLIO_WORKSPACE")
			return 2
		}
		script := workers.NewScriptExecutor(adaptersDir, workBase)
		script.Workspace = workspace
		script.Context = ctx
		settings, err := localWorkerSettings(dataDir)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			return 2
		}
		script.Executors = settings.Executors
		script.WorkerEnv = settings.WorkerEnv
		exec = script
	} else {
		fakeExec, err := loadFakeExecutor(fakeConfigPath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "error: %v\n", err)
			return 1
		}
		exec = fakeExec
	}

	store, err := openStore(dataDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		return 1
	}
	defer store.Close()

	engine := plan.NewEngineWithStore(p, exec, store)
	engine.Context = ctx

	runID, err := engine.CreateRun(inputData)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: creating run: %v\n", err)
		return 1
	}

	if err := engine.Run(runID); err != nil {
		// Even on failure, emit JSON so the test harness can inspect it.
		run, _ := engine.Store().GetRun(runID)
		if jsonOut && run != nil {
			attempts, _ := engine.Store().ListExecutionAttempts(runID, "")
			out, _ := diagnostic.JSON(map[string]any{
				"diagnostics": state.AttemptDiagnostics(attempts),
				"runId":       runID,
				"state":       run.State,
				"error":       run.Error,
				"output":      run.Output,
				"events":      formatEvents(mustEvents(engine.Store(), runID)),
			})
			// Preserve the typed numeric usage summary outside diagnostic key
			// redaction, which treats any key containing "token" as a secret.
			var response map[string]any
			_ = json.Unmarshal(out, &response)
			response["usage"] = state.SummarizeUsage(attempts)
			out, _ = json.Marshal(response)
			fmt.Println(string(out))
			return 1
		}
		fmt.Fprintf(os.Stderr, "error: run failed: %v\n", err)
		return 1
	}

	run, _ := engine.Store().GetRun(runID)
	events := mustEvents(engine.Store(), runID)

	if jsonOut {
		attempts, _ := engine.Store().ListExecutionAttempts(runID, "")
		out, _ := json.MarshalIndent(map[string]any{
			"usage":  state.SummarizeUsage(attempts),
			"runId":  runID,
			"state":  run.State,
			"output": run.Output,
			"events": formatEvents(events),
		}, "", "  ")
		fmt.Println(string(out))
	} else {
		fmt.Printf("run %s: %s\n", runID, run.State)
		if run.Output != nil {
			out, _ := json.MarshalIndent(run.Output, "", "  ")
			fmt.Printf("output:\n%s\n", string(out))
		}
		fmt.Printf("events: %d\n", len(events))
	}
	return 0
}

func localWorkerSettings(dataDir string) (serviceConfig, error) {
	raw, err := os.ReadFile(authConfigPath(dataDir))
	if os.IsNotExist(err) {
		return serviceConfig{}, nil
	}
	if err != nil {
		return serviceConfig{}, err
	}
	var cfg serviceConfig
	if err := json.Unmarshal(raw, &cfg); err != nil {
		return serviceConfig{}, fmt.Errorf("config: %w", err)
	}
	if err := workers.ValidateWorkerEnv(cfg.WorkerEnv); err != nil {
		return cfg, fmt.Errorf("workerEnv: %w", err)
	}
	return cfg, workers.ValidateExecutorConfigs(cfg.Executors)
}

func mustEvents(store state.Store, runID string) []state.Event {
	events, err := store.GetEvents(runID, 0, 0)
	if err != nil {
		return nil
	}
	return events
}

func formatEvents(events []state.Event) []map[string]any {
	out := make([]map[string]any, len(events))
	for i, e := range events {
		out[i] = map[string]any{
			"seq":       e.Seq,
			"type":      e.Type,
			"subjectId": e.SubjectID,
			"timestamp": e.Timestamp,
		}
		if e.Payload != nil {
			out[i]["payload"] = e.Payload
		}
	}
	return out
}

func strOrDefault(s, def string) string {
	if s == "" {
		return def
	}
	return s
}

// cmdRunRemote compiles the workflow locally, submits it to a remote coordinator,
// and then polls until the run reaches a terminal state, printing progress as
// events arrive. This is semantically equivalent to `muxlio submit` followed by
// `muxlio status`, but in a single blocking call.
func cmdRunRemote(ctx context.Context, planPath, inputPath, dataDir, serverArg, tokenFlagVal, tokenFileFlagVal string, jsonOut bool) int {
	serverURL, profileToken, err := resolveServer(serverArg, dataDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		return 2
	}
	token := loadToken(tokenFlagVal, tokenFileFlagVal)
	if token == "" {
		token = profileToken
	}

	// 1. Compile / load plan locally.
	p, err := loadPlan(planPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		return 1
	}
	if verrs := plan.ErrorsOnly(plan.Validate(p)); len(verrs) > 0 {
		fmt.Fprintf(os.Stderr, "error: plan has %d validation error(s)\n", len(verrs))
		for _, ve := range verrs {
			fmt.Fprintf(os.Stderr, "  %s: %s\n", ve.Code, ve.Message)
		}
		return 1
	}

	// 2. Read input (default to {}).
	var inputData []byte
	if inputPath != "" {
		inputData, err = os.ReadFile(inputPath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "error: reading input: %v\n", err)
			return 1
		}
	} else {
		inputData = []byte("{}")
	}

	// 3. Submit to coordinator.
	planBytes, err := json.Marshal(p)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: marshalling plan: %v\n", err)
		return 1
	}
	submitBody, _ := json.Marshal(map[string]json.RawMessage{
		"plan":  json.RawMessage(planBytes),
		"input": json.RawMessage(inputData),
	})
	submitReq, err := http.NewRequestWithContext(ctx, http.MethodPost, serverURL+"/v1/runs", bytes.NewReader(submitBody))
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: creating request: %v\n", err)
		return 1
	}
	submitReq.Header.Set("Content-Type", "application/json")
	setAuthHeader(submitReq, token)
	client := &http.Client{Timeout: 30 * time.Second}
	resp, err := client.Do(submitReq)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: submitting run to %s: %v\n", serverURL, err)
		return 1
	}
	defer resp.Body.Close()
	submitRaw, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		fmt.Fprintf(os.Stderr, "error: coordinator returned HTTP %d: %s\n", resp.StatusCode, submitRaw)
		return 1
	}
	var submitResult struct {
		RunID string `json:"runId"`
	}
	if err := json.Unmarshal(submitRaw, &submitResult); err != nil || submitResult.RunID == "" {
		fmt.Fprintf(os.Stderr, "error: unexpected submit response: %s\n", submitRaw)
		return 1
	}
	runID := submitResult.RunID
	if !jsonOut {
		fmt.Printf("submitted run %s to %s\n", runID, serverURL)
	}

	// 4. Poll until terminal.
	terminal := map[string]bool{"succeeded": true, "failed": true, "cancelled": true}
	pollURL := serverURL + "/v1/runs/" + url.PathEscape(runID)
	for {
		select {
		case <-ctx.Done():
			fmt.Fprintf(os.Stderr, "\ncancelled\n")
			return 1
		case <-time.After(2 * time.Second):
		}
		pollReq, err := http.NewRequestWithContext(ctx, http.MethodGet, pollURL, nil)
		if err != nil {
			fmt.Fprintf(os.Stderr, "error: polling: %v\n", err)
			return 1
		}
		setAuthHeader(pollReq, token)
		pollResp, err := client.Do(pollReq)
		if err != nil {
			// Network blip — keep retrying until context cancels.
			continue
		}
		pollRaw, _ := io.ReadAll(io.LimitReader(pollResp.Body, 4<<20))
		pollResp.Body.Close()
		if pollResp.StatusCode != http.StatusOK {
			continue
		}
		var run struct {
			ID          string                  `json:"id"`
			State       string                  `json:"state"`
			Output      any                     `json:"output,omitempty"`
			Error       string                  `json:"error,omitempty"`
			Diagnostics []diagnostic.Diagnostic `json:"diagnostics,omitempty"`
		}
		if err := json.Unmarshal(pollRaw, &run); err != nil {
			continue
		}
		if !jsonOut {
			fmt.Printf("\r  run %s: %-12s", runID, run.State)
		}
		if terminal[run.State] {
			if jsonOut {
				out, _ := diagnostic.JSON(map[string]any{
					"diagnostics": run.Diagnostics,
					"runId":       runID,
					"state":       run.State,
					"output":      run.Output,
					"error":       run.Error,
					"server":      serverURL,
				})
				fmt.Println(string(out))
			} else {
				fmt.Printf("\nrun %s: %s\n", runID, run.State)
				if run.Output != nil {
					outRaw, _ := json.MarshalIndent(run.Output, "", "  ")
					fmt.Printf("output:\n%s\n", string(outRaw))
				}
				if run.Error != "" {
					fmt.Fprintf(os.Stderr, "error: %s\n", run.Error)
				}
			}
			if run.State == "succeeded" {
				return 0
			}
			return 1
		}
	}
}

func emitDiagnostic(path string, err error, jsonOut bool) {
	d := diagnostic.New("MUXLIO_BUILD_FAILED", "build", err.Error(), "Correct the source file or compiler error and rerun check --json.")
	d.Source = &diagnostic.Source{File: path}
	var syntax *json.SyntaxError
	if errors.As(err, &syntax) {
		d.Code = "MUXLIO_INVALID_JSON"
		if raw, readErr := os.ReadFile(path); readErr == nil && syntax.Offset > 0 && syntax.Offset <= int64(len(raw)) {
			before := string(raw[:syntax.Offset-1])
			d.Source.Line = strings.Count(before, "\n") + 1
			d.Source.Column = len(before) - strings.LastIndex(before, "\n")
		}
	}
	d.Identify()
	if jsonOut {
		b, _ := diagnostic.JSON(map[string]any{"valid": false, "errors": []diagnostic.Diagnostic{d}})
		fmt.Println(string(b))
	} else {
		fmt.Fprintln(os.Stderr, diagnostic.Redact(d.Error()))
		fmt.Fprintln(os.Stderr, "fix:", d.Fix)
	}
}
